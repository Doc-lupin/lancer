"""Generate first-pass 3D positions (light-years) for region centers.

Starts from the official chart layout (coreward = +y, trailing = +x),
adds depth on z and some jitter so the Basin reads as a rough sphere
about 50 ly across rather than a flat grid. Output is meant to be
adjusted by hand afterward.

Usage: python3 tools/generate_positions.py [seed]
"""
import json, math, random, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGIONS = ROOT / "data/parsed/regions.json"
OUT = ROOT / "data/parsed/positions.json"

SEED = int(sys.argv[1]) if len(sys.argv) > 1 else 5029
RADIUS = 25.0          # Basin is ~50 ly across
CHART_ORIGIN = (672, 918)   # Ostrom's box center on the chart
PX_PER_LY = 38.0       # chart pixels per light-year before jitter
JITTER_XY = 2.0
DEPTH = 9.0            # max |z| for inner regions
MIN_SEP = 3.5          # minimum ly between region centers

rng = random.Random(SEED)
regions = json.loads(REGIONS.read_text())["regions"]

def place(r):
    cx, cy = r["chartPos"]
    x = (cx - CHART_ORIGIN[0]) / PX_PER_LY + rng.uniform(-JITTER_XY, JITTER_XY)
    y = -(cy - CHART_ORIGIN[1]) / PX_PER_LY + rng.uniform(-JITTER_XY, JITTER_XY)
    # Frontier regions get more depth so the arms curl around the sphere.
    zmax = DEPTH * (1.4 if r["frontier"] else 1.0)
    z = rng.uniform(-zmax, zmax)
    if r["arm"] == "crossroads":
        z *= 0.3  # keep the crossroads near the middle
    return [x, y, z]

pos = {r["id"]: place(r) for r in regions}

# Keep hand-placed values: anything marked "locked" in the existing file.
locked = {}
if OUT.exists():
    for i, v in json.loads(OUT.read_text())["regions"].items():
        if v.get("locked"):
            locked[i] = v["pos"]
pos.update({i: list(p) for i, p in locked.items()})

# The Quiet is beyond the map: push it outside the charted sphere,
# on the far side of Ostrom from the rest of the Basin.
if "quiet" not in locked:
    pos["quiet"] = [6.0, 1.0, -(RADIUS + 6.0)]

# Fit to the sphere, then push apart anything too close.
for _ in range(200):
    moved = False
    ids = [i for i in pos if i != "quiet"]
    for i in ids:
        if i in locked:
            continue
        p = pos[i]
        d = math.dist(p, (0, 0, 0))
        if d > RADIUS - 1:
            pos[i] = [c * (RADIUS - 1) / d for c in p]
    for a in range(len(ids)):
        for b in range(a + 1, len(ids)):
            pa, pb = pos[ids[a]], pos[ids[b]]
            d = math.dist(pa, pb)
            if d < MIN_SEP:
                push = (MIN_SEP - d) / 2 + 0.01
                v = [(pa[k] - pb[k]) / (d or 1) for k in range(3)]
                # A locked region doesn't move; the other one takes the full push.
                fa = 0 if ids[a] in locked else (1 if ids[b] not in locked else 2)
                fb = 0 if ids[b] in locked else (1 if ids[a] not in locked else 2)
                for k in range(3):
                    pa[k] += v[k] * push * fa
                    pb[k] -= v[k] * push * fb
                moved = True
    if not moved:
        break

out = {
    "_source": f"Generated by tools/generate_positions.py (seed {SEED}). Units: light-years. "
               "Axes: +x trailing, -x spinward, +y coreward, -y rimward, z depth. "
               "Origin is near Ostrom. Edit by hand freely; set 'locked': true to mark a hand-placed value.",
    "seed": SEED,
    "regions": {i: {"pos": [round(c, 2) for c in p], "locked": i in locked} for i, p in pos.items()},
}
OUT.write_text(json.dumps(out, indent=2) + "\n")
print(f"wrote {OUT.relative_to(ROOT)}")
